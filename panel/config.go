// cfgMarker starts every configuration the panel writes. A configuration
// file without it is backed up before it is replaced for the first time.
const cfgMarker = "# Generated by 3proxy-panel"

// defaultHeader holds the global settings put on top of the generated
// configuration unless a header file is given.
const defaultHeader = `nserver 1.1.1.1
nserver 8.8.8.8
nscache 65536
timeouts 1 5 30 60 180 1800 15 60
`

// renderConfig builds the 3proxy configuration for the enabled proxies.
// Every proxy is a service of its own with an access list that admits its
// user only. path is the configuration file as 3proxy sees it, inside its
// chroot if chrooted is set.
func renderConfig(list []Proxy, header, path string, chrooted bool) []byte {
	var b bytes.Buffer
	b.WriteString(cfgMarker + ". Do not edit: changes are overwritten by the panel.\n\n")
	b.WriteString(header)
	if header != "" && !strings.HasSuffix(header, "\n") {
		b.WriteByte('\n')
	}
	if chrooted {
		// The file 3proxy was started with is outside the chroot, so a
		// reload has to read this one.
		fmt.Fprintf(&b, "config %s\n", path)
	}
	// 3proxy reloads within a minute when the file changes, even if the
	// reload command is not available.
	fmt.Fprintf(&b, "monitor %s\n", path)

	var enabled []Proxy
	users := map[string]string{}
	for _, p := range list {
		if p.Enabled {
			enabled = append(enabled, p)
			users[p.Username] = p.Password
		}
	}
	if len(enabled) == 0 {
		return b.Bytes()
	}

	names := make([]string, 0, len(users))
	for u := range users {
		names = append(names, u)
	}
	sort.Strings(names)
	b.WriteString("\nauth strong\n")
	for _, u := range names {
		fmt.Fprintf(&b, "users \"%s:CL:%s\"\n", u, users[u])
	}

	for _, p := range enabled {
		fmt.Fprintf(&b, "\n# %s\nflush\n", p.ID)
		// Proxy users must not reach services on the VPS itself, the panel
		// among them.
		b.WriteString("deny * * 127.0.0.0/8\n")
		fmt.Fprintf(&b, "allow %s\n", p.Username)
		fmt.Fprintf(&b, "%s -p%d", proxyServices[p.Type], p.Port)
		if p.ExtIP != "" {
			fmt.Fprintf(&b, " -e%s", p.ExtIP)
		}
		b.WriteByte('\n')
	}
	return b.Bytes()
}

// writeConfig replaces the 3proxy configuration, keeping a copy of a file
// the panel did not write.
func writeConfig(path string, data []byte) error {
	old, err := os.ReadFile(path)
	if err == nil && len(bytes.TrimSpace(old)) > 0 && !bytes.HasPrefix(old, []byte(cfgMarker)) {
		backup := fmt.Sprintf("%s.bak-%s", path, time.Now().Format("20060102-150405"))
		if err := copyFile(path, backup); err != nil {
			return fmt.Errorf("backup %s: %w", path, err)
		}
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return writeFileAtomic(path, data, 0o640, true)
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	fi, err := in.Stat()
	if err != nil {
		return err
	}
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_EXCL, fi.Mode().Perm())
	if err != nil {
		return err
	}
	if _, err := io.Copy(out, in); err != nil {
		out.Close()
		return err
	}
	return out.Close()
}

func chownLike(path string, fi os.FileInfo) {
	if st, ok := fi.Sys().(*syscall.Stat_t); ok {
		// Only root may give a file away; otherwise it stays ours.
		_ = os.Chown(path, int(st.Uid), int(st.Gid))
	}
}

// runReload runs the reload command, if any. It is split on spaces and run
// without a shell.
func runReload(command string) error {
	args := strings.Fields(command)
	if len(args) == 0 {
		return nil
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, args[0], args[1:]...).CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			return err
		}
		return fmt.Errorf("%v: %s", err, msg)
	}
	return nil
}
